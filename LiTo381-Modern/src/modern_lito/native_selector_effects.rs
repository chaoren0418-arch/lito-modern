pub fn qualify(c:&SpriteActionCatalog)->Result<Vec<(u32,u8,Animation)>,HonorAssetError> {
    let mut result=Vec::with_capacity(SPECS.len());
    for s in SPECS {
        let row=c.sprites.get(&s.sprite).ok_or(HonorAssetError::Unsupported("selector effect absent"))?;
        let resolved=c.resolve_action(s.sprite,ActionKey::new(0))?;let a=resolved.animation;
        if row.id!=s.sprite || row.graphics_id!=s.bank || row.image_count!=Some(1)
            || row.header_issue.is_some() || row.header_bytes.as_slice()!=s.header || row.actions.len()!=1
            || resolved.definition_sprite_id!=s.sprite || row.attributes.len()!=s.attributes.len()
            || row.attributes.iter().zip(s.attributes).any(|(a,(key,label,body))|
                a.key!=ActionKey::new(*key) || a.label_bytes.as_slice()!=*label || a.body_bytes.as_slice()!=*body)
            || a.directionality!=Directionality::Undirected || a.frames_per_second!=24 || a.frames.len()!=s.frames.len()
            || a.frames.iter().zip(s.frames).any(|(a,(image,subframe,ticks,events))|
                a.image_id!=*image || a.subframe!=*subframe || a.duration_ticks!=*ticks || a.events.as_slice()!=*events) {
            return Err(HonorAssetError::Unsupported("selector effect original definition changed"));
        }
        result.push((s.sprite,0,a.clone()));
    }
    Ok(result)
}
